#Logical OP
a = 10
b = 15
print("a > b and a != b:", a > b and a != b)
print("a < b or a != b:", a < b or a != b)
print("not(a > b):", not(a > b))

#Bitwise OP
p = 10
Q = 4

print("p & Q", p & Q)
print("p | Q(OR)", p | Q)
print("p ^ Q(XOR)", p ^ Q)
print("~Q(NOT)", ~Q)
print("p << 1", p << 1)
print("p >> 1", p >> 1)
