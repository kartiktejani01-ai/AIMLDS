# for Loop
fruits = ["apple" , "banana" , "cherry"]
for x in fruits:
    print(x)

# Looping through a String
for x in "banana":
    print(x)

# The break statement
fruits = ["apple" , "banana" , "cherry"]
for x in fruits:
    print(x)
    if x == "banana":
        break

# The continue Statement
fruits = ["apple", "banana", "cherry"]
for x in fruits:
    if x == "banana":
        continue
    print(x)

# The range() Function
for x in range(6):
    print(x)

# increment the sequencr with 3
for x in range(2, 30, 3):
    print(x)

